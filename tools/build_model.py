"""Generate reviewable PostgreSQL DDL, dictionary and empty Sheets templates."""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from database.model import TABLES, COMPOSITE_KEYS, METADATA


def build():
    for folder in ('docs', 'sample_data/sheets'):
        (ROOT / folder).mkdir(parents=True, exist_ok=True)
    sql = ['-- Generated by python tools/build_model.py; PostgreSQL 16+.\nBEGIN;']
    dictionary = ['# Data dictionary', '', 'Generated from `database/model.py`. Each operational table is one Google Sheets tab.', '', 'IDs are server-generated UUID strings; compound keys are listed below. Dates use ISO 8601; timestamps use UTC. Currency is INR, stored as exact decimals. Blank CSV cells mean NULL, never zero. Metadata is server managed.', '']
    manifest = {}
    for name, fields in TABLES.items():
        columns = fields + METADATA
        definitions = [f'    {key} {kind} {rule}'.rstrip() for key, kind, rule in columns]
        if name in COMPOSITE_KEYS:
            definitions.append(f'    PRIMARY KEY ({COMPOSITE_KEYS[name]})')
        sql.append(f'CREATE TABLE {name} (\n' + ',\n'.join(definitions) + '\n);')
        dictionary += [f'## {name}', '', f'Primary key: `{COMPOSITE_KEYS.get(name, next((f[0] for f in fields if "PRIMARY KEY" in f[2]), ""))}`.', '', '| Column | PostgreSQL type | Rules |', '| --- | --- | --- |']
        dictionary += [f'| {key} | {kind} | {rule or "Optional"} |' for key, kind, rule in columns]
        dictionary.append('')
        with (ROOT / 'sample_data/sheets' / f'{name}.csv').open('w', newline='', encoding='utf-8') as handle:
            csv.writer(handle).writerow([f[0] for f in columns])
        manifest[name] = [{'name': key, 'type': kind, 'rules': rule} for key, kind, rule in columns]
    sql += ["""CREATE FUNCTION touch_record() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF current_setting('superstore.preserve_metadata', true) = 'on' THEN RETURN NEW; END IF;
NEW.updated_at = CURRENT_TIMESTAMP; NEW.version = OLD.version + 1; RETURN NEW;
END;
$$;"""]
    for name in TABLES:
        sql.append(f'CREATE TRIGGER touch_{name} BEFORE UPDATE ON {name} FOR EACH ROW EXECUTE FUNCTION touch_record();')
    sql += ['COMMIT;', '']
    (ROOT / 'database/schema.sql').write_text('\n\n'.join(sql), encoding='utf-8')
    (ROOT / 'docs/data_dictionary.md').write_text('\n'.join(dictionary), encoding='utf-8')
    (ROOT / 'database/sheets_manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(f'Generated {len(TABLES)} tables, dictionary and Sheets templates.')


if __name__ == '__main__':
    build()
