"""Generate Apps Script configuration and dedicated page templates from the model."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from database.model import TABLES, METADATA, COMPOSITE_KEYS, DISPLAY_CODES

PAGES = {
    'Dashboard': ('Store overview', 'Sales, margin and stock signals from your operational records.', None, None),
    'ProductList': ('Products', 'Search your catalogue, review prices and maintain product status.', 'products', 'ProductForm'),
    'ProductForm': ('Product details', 'Maintain identifiers, classification, prices and tax codes.', 'products', 'master'),
    'Categories': ('Categories', 'Organize categories and their parent relationships.', 'categories', 'master'),
    'Customers': ('Customers', 'Customer profiles, segments and contact information.', 'customers', 'CustomerForm'),
    'CustomerForm': ('Customer details', 'Create or update an individual or business customer.', 'customers', 'master'),
    'Suppliers': ('Suppliers', 'Manage your supplier network and purchasing terms.', 'suppliers', 'SupplierForm'),
    'SupplierForm': ('Supplier details', 'Maintain supplier contacts, lead times and account status.', 'suppliers', 'master'),
    'PurchaseOrders': ('Purchase orders', 'Create approved purchase orders with multiple product lines.', 'purchase_orders', 'purchase'),
    'GoodsReceipts': ('Goods receipts', 'Receive purchase lines and post accepted quantities to stock.', 'goods_receipts', 'receive'),
    'Inventory': ('Inventory', 'Available stock, reorder points, adjustments and store transfers.', 'inventory_balances', 'adjust'),
    'StockMovements': ('Stock movements', 'An auditable ledger of receipts, sales, returns and transfers.', 'inventory_movements', None),
    'SalesOrders': ('Sales orders & payments', 'Review completed counter sales and record payments independently.', 'sales_orders', 'payment'),
    'SalesForm': ('New sale', 'Select products and quantities; historical price and cost snapshots are preserved.', 'sales_order_items', 'sale'),
    'Returns': ('Returns & refunds', 'Accept original order lines, decide restocking and settle refunds.', 'returns', 'returnOrder'),
    'Shipping': ('Shipping', 'Dispatch orders and track delivery with carrier references.', 'shipments', 'ship'),
    'Reports': ('Reports', 'Inspect operational totals and export source records for analysis.', None, None),
    'Users': ('Administration', 'Manage authorized users, roles, stores, brands, segments and addresses.', 'users', 'master'),
    'AuditLogs': ('Audit logs', 'Review actor, time, entity changes and transaction details.', 'audit_logs', None),
}


def build():
    target = ROOT / 'apps-script'
    target.mkdir(exist_ok=True)
    model = {t: [dict(name=n, type=k, rules=r) for n, k, r in fields + METADATA] for t, fields in TABLES.items()}
    (target / 'Config.gs').write_text('// Generated by tools/build_portal.py\nconst MODEL = ' + json.dumps(model, indent=2) + ';\nconst COMPOSITE_KEYS = ' + json.dumps({t: keys.split(', ') for t, keys in COMPOSITE_KEYS.items()}) + ';\nconst DISPLAY_CODES = ' + json.dumps(DISPLAY_CODES) + ';\n', encoding='utf-8')
    registry = {name: dict(title=title, description=desc, table=table, form=form) for name, (title, desc, table, form) in PAGES.items()}
    (target / 'Router.gs').write_text('const PAGES = ' + json.dumps(registry, indent=2) + ';\nfunction include_(name) {\n  if (!/^(Partial_|Page_)/.test(name)) throw new Error("Invalid template");\n  return HtmlService.createHtmlOutputFromFile(name).getContent();\n}\n', encoding='utf-8')
    for name, (title, desc, table, form) in PAGES.items():
        content = f'<section class="page" id="page-{name}" hidden data-table="{table or ""}" data-form="{form or ""}">\n<header class="page-heading"><div><p class="eyebrow">SUPERSTORE / OPERATIONS</p><h1>{title}</h1><p>{desc}</p></div></header>\n'
        if name == 'Dashboard':
            content += '<div id="kpis" class="kpis"></div><div class="panel"><h2>Daily workspace</h2><p>Record a sale, receive purchased goods, or review low-stock products.</p><div class="quick-links"><button data-page="SalesForm">Create sale</button><button data-page="GoodsReceipts">Receive stock</button><button data-page="Inventory">Review inventory</button></div></div><div class="panel"><h2>Low-stock watchlist</h2><div id="low-stock"></div></div>'
        elif name == 'Reports':
            content += '<div class="panel"><h2>Operational reports</h2><p>Totals include completed sales and accepted returns, excluding tax. Historical sale dates are restated when returns are accepted. Use the Streamlit dashboard for date, store and category analysis.</p><div id="report-kpis" class="kpis"></div><label>Export table<select id="export-table"></select></label><button id="export-csv">Download CSV</button></div>'
        else:
            content += '<div class="panel"><div class="toolbar"><label>Search records<input class="table-search" type="search" placeholder="Search any column"></label><button class="export-table">Export CSV</button></div><div class="table-host"></div><div class="pagination"></div></div>'
            if form:
                content += '<div class="panel form-panel"><h2 class="form-title">'+('Create / edit record' if form=='master' else 'New transaction')+'</h2><div class="form-host"></div></div>'
            if name == 'Inventory':
                content += '<div class="panel"><h2>Transfer stock</h2><div id="transfer-form"></div></div>'
            if name == 'Returns':
                content += '<div class="panel"><h2>Settle refund</h2><div id="refund-form"></div></div>'
            if name == 'Users':
                content += '<div class="panel"><label>Administration table<select id="admin-table"><option>users</option><option>roles</option><option>stores</option><option>brands</option><option>segments</option><option>customer_addresses</option><option>product_suppliers</option></select></label></div>'
        (target / f'Page_{name}.html').write_text(content+'\n</section>\n', encoding='utf-8')
    links = ''.join(f'<button data-page="{name}"'+(' data-admin="true"' if name in ('Users','AuditLogs') else '')+f'>{title.split(" &")[0]}</button>' for name,(title,*_) in PAGES.items() if not name.endswith('Form'))
    (target / 'Partial_Sidebar.html').write_text('<aside class="sidebar"><div class="brand"><span class="brand-icon">S</span><div>SUPERSTORE<small>Retail workspace</small></div></div><nav aria-label="Main navigation">'+links+'</nav><div class="sidebar-foot">Operations + intelligence<br><span id="sidebar-identity"></span></div></aside>', encoding='utf-8')
    includes='\n'.join("<?!= include_('Page_"+name+"'); ?>" for name in PAGES)
    (target / 'Index.html').write_text('''<!DOCTYPE html>
<html><head><base target="_top"><meta name="viewport" content="width=device-width, initial-scale=1">
<?!= include_('Partial_Styles'); ?></head><body>
<?!= include_('Partial_Sidebar'); ?><div class="workspace">
<?!= include_('Partial_Header'); ?><main>'''+includes+'''</main></div>
<?!= include_('Partial_Modal'); ?>
<?!= include_('Partial_CoreJS'); ?>
<?!= include_('Partial_ProductsJS'); ?>
<?!= include_('Partial_CustomersJS'); ?>
<?!= include_('Partial_InventoryJS'); ?>
<?!= include_('Partial_OrdersJS'); ?>
<script>start();</script></body></html>''', encoding='utf-8')
    print(f'Generated {len(PAGES)} dedicated portal pages and schema configuration.')


if __name__ == '__main__':
    build()
